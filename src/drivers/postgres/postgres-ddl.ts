import type { Client } from 'pg'

import type { ObjectKind, ObjectRef } from '../../core/engine/catalog.ts'
import { qualifiedName, quoteIdentifier } from '../../core/engine/dialect.ts'
import {
  type JsonRecord,
  readBoolean,
  readNullableString,
  readNumber,
  readString,
} from '../../core/json/record.ts'
import { queryRows } from './postgres-catalog.ts'
import { POSTGRES_DIALECT } from './postgres-dialect.ts'

const RELATION = `SELECT c.oid AS oid, c.relkind::text AS kind, pg_get_partkeydef(c.oid) AS "partitionKey",
  CASE WHEN c.relkind IN ('v', 'm') THEN pg_get_viewdef(c.oid, true) END AS "viewDefinition"
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = $1 AND c.relname = $2`

const COLUMNS = `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS "dataType",
  a.attnotnull AS "isNotNull", pg_get_expr(d.adbin, d.adrelid) AS expression,
  a.attidentity::text AS identity, a.attgenerated::text AS generated
FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`

// Primary key first, then unique, check and exclusion constraints, then foreign keys.
const CONSTRAINTS = `SELECT conname AS name, pg_get_constraintdef(oid, true) AS definition
FROM pg_constraint
WHERE conrelid = $1 AND contype IN ('p', 'u', 'c', 'x', 'f')
ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'x' THEN 3 ELSE 4 END, conname`

// The indexes that no constraint created.
const INDEXES = `SELECT pg_get_indexdef(i.indexrelid) AS definition
FROM pg_index i JOIN pg_class ic ON ic.oid = i.indexrelid
WHERE i.indrelid = $1
  AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = i.indexrelid AND c.conrelid = i.indrelid)
ORDER BY ic.relname`

const INDENT = '    '
const IDENTITIES: ReadonlyMap<string, string> = new Map([
  ['a', ' GENERATED ALWAYS AS IDENTITY'],
  ['d', ' GENERATED BY DEFAULT AS IDENTITY'],
])
const GENERATED: ReadonlyMap<string, string> = new Map([
  ['s', 'STORED'],
  ['v', 'VIRTUAL'],
])
const CREATE_KEYWORDS: ReadonlyMap<string, string> = new Map([
  ['v', 'CREATE OR REPLACE VIEW'],
  ['m', 'CREATE MATERIALIZED VIEW'],
  ['f', 'CREATE FOREIGN TABLE'],
])
const FOREIGN_TABLE = 'f'
const FOREIGN_TABLE_NOTE = '-- A foreign table: its server and options are not shown.\n'

export interface TableColumn {
  readonly name: string
  readonly dataType: string
  readonly isNotNull: boolean
  readonly expression: string | undefined
  readonly identity: string
  readonly generated: string
}

export interface TableParts {
  readonly kind: string
  readonly name: string
  readonly columns: readonly TableColumn[]
  readonly constraints: readonly string[]
  readonly indexes: readonly string[]
  readonly partitionKey: string | undefined
}

// PostgreSQL has no SHOW CREATE TABLE: the statement is rebuilt from the catalog. Views come from
// pg_get_viewdef.
export async function objectDdl(
  client: Client,
  object: ObjectRef,
  kind: ObjectKind,
): Promise<string> {
  const [relation] = await queryRows(client, RELATION, [object.schema, object.name])
  if (relation === undefined) {
    throw new Error(`PostgreSQL has no ${kind} named ${object.schema}.${object.name}`)
  }
  const name = qualifiedName(POSTGRES_DIALECT, [object.schema, object.name])
  const viewDefinition = readNullableString(relation, 'viewDefinition')
  if (viewDefinition !== undefined) {
    return `${String(CREATE_KEYWORDS.get(readString(relation, 'kind')))} ${name} AS\n${viewDefinition.trim()}`
  }
  return tableDdl(await tableParts(client, relation, name))
}

async function tableParts(client: Client, relation: JsonRecord, name: string): Promise<TableParts> {
  const oid = readNumber(relation, 'oid')
  const [columns, constraints, indexes] = await Promise.all([
    queryRows(client, COLUMNS, [oid]),
    queryRows(client, CONSTRAINTS, [oid]),
    queryRows(client, INDEXES, [oid]),
  ])
  return {
    kind: readString(relation, 'kind'),
    name,
    columns: columns.map(readColumn),
    constraints: constraints.map(
      (row) =>
        `CONSTRAINT ${quoteIdentifier(POSTGRES_DIALECT, readString(row, 'name'))} ${readString(row, 'definition')}`,
    ),
    indexes: indexes.map((row) => readString(row, 'definition')),
    partitionKey: readNullableString(relation, 'partitionKey'),
  }
}

function readColumn(row: JsonRecord): TableColumn {
  return {
    name: readString(row, 'name'),
    dataType: readString(row, 'dataType'),
    isNotNull: readBoolean(row, 'isNotNull'),
    expression: readNullableString(row, 'expression'),
    identity: readString(row, 'identity'),
    generated: readString(row, 'generated'),
  }
}

export function tableDdl(parts: TableParts): string {
  const lines = [...parts.columns.map(columnDefinition), ...parts.constraints]
  const body = lines.map((line) => INDENT + line).join(',\n')
  const create =
    parts.kind === FOREIGN_TABLE ? `${FOREIGN_TABLE_NOTE}CREATE FOREIGN TABLE` : 'CREATE TABLE'
  const partition = parts.partitionKey === undefined ? '' : ` PARTITION BY ${parts.partitionKey}`
  const table = `${create} ${parts.name} (\n${body}\n)${partition};`
  return [table, ...parts.indexes.map((index) => `${index};`)].join('\n\n')
}

function columnDefinition(column: TableColumn): string {
  const notNull = column.isNotNull ? ' NOT NULL' : ''
  return `${quoteIdentifier(POSTGRES_DIALECT, column.name)} ${column.dataType}${valueClause(column)}${notNull}`
}

// An identity, a generated expression or a default: a column has at most one of them.
function valueClause(column: TableColumn): string {
  const identity = IDENTITIES.get(column.identity)
  if (identity !== undefined || column.expression === undefined) {
    return identity ?? ''
  }
  const generated = GENERATED.get(column.generated)
  return generated === undefined
    ? ` DEFAULT ${column.expression}`
    : ` GENERATED ALWAYS AS (${column.expression}) ${generated}`
}
