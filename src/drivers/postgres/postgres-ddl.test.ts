import { beforeEach, describe, expect, it, vi } from 'vitest'

import { answerBy, pg, pgRequest } from '../../../test/fakes/pg.ts'
import { ObjectKind } from '../../core/engine/catalog.ts'
import type { EngineSession } from '../../core/engine/engine.ts'
import { type TableColumn, tableDdl } from './postgres-ddl.ts'
import { postgresEngine } from './postgres-engine.ts'

vi.mock('pg', async (importOriginal) => {
  const original = await importOriginal<{ default: object }>()
  const { FakeClient } = await import('../../../test/fakes/pg.ts')
  return { default: { ...original.default, Client: FakeClient } }
})

const ORDERS = { database: 'shop', schema: 'sales', name: 'orders' }

function column(name: string, changes: Partial<TableColumn> = {}): TableColumn {
  return {
    name,
    dataType: 'bigint',
    isNotNull: false,
    expression: undefined,
    identity: '',
    generated: '',
    ...changes,
  }
}

async function connected(): Promise<EngineSession> {
  return postgresEngine.connect(pgRequest())
}

beforeEach(() => {
  pg.reset()
})

describe('tableDdl', () => {
  it('should write each column with its identity, generated expression, default and nullability', () => {
    expect(
      tableDdl({
        kind: 'r',
        name: '"sales"."orders"',
        columns: [
          column('id', { isNotNull: true, identity: 'a' }),
          column('seq', { identity: 'd', isNotNull: true }),
          column('total', { dataType: 'numeric(20,6)', expression: '0', isNotNull: true }),
          column('double', { expression: '(total * 2)', generated: 's' }),
          column('half', { expression: '(total / 2)', generated: 'v' }),
          column('Note', { dataType: 'text' }),
        ],
        constraints: ['CONSTRAINT "orders_pkey" PRIMARY KEY (id)'],
        indexes: ['CREATE INDEX orders_total ON sales.orders USING btree (total)'],
        partitionKey: undefined,
      }),
    ).toBe(
      [
        'CREATE TABLE "sales"."orders" (',
        '    "id" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,',
        '    "seq" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,',
        '    "total" numeric(20,6) DEFAULT 0 NOT NULL,',
        '    "double" bigint GENERATED ALWAYS AS ((total * 2)) STORED,',
        '    "half" bigint GENERATED ALWAYS AS ((total / 2)) VIRTUAL,',
        '    "Note" text,',
        '    CONSTRAINT "orders_pkey" PRIMARY KEY (id)',
        ');',
        '',
        'CREATE INDEX orders_total ON sales.orders USING btree (total);',
      ].join('\n'),
    )
  })

  it('should write the partition key and say what a foreign table leaves out', () => {
    expect(
      tableDdl({
        kind: 'p',
        name: '"t"',
        columns: [column('a')],
        constraints: [],
        indexes: [],
        partitionKey: 'RANGE (a)',
      }),
    ).toBe('CREATE TABLE "t" (\n    "a" bigint\n) PARTITION BY RANGE (a);')
    expect(
      tableDdl({
        kind: 'f',
        name: '"f"',
        columns: [column('a')],
        constraints: [],
        indexes: [],
        partitionKey: undefined,
      }),
    ).toBe(
      '-- A foreign table: its server and options are not shown.\nCREATE FOREIGN TABLE "f" (\n    "a" bigint\n);',
    )
  })
})

describe('objectDdl', () => {
  it('should rebuild a table from the catalog of its database', async () => {
    answerBy([
      [
        'SELECT c.oid',
        { rows: [{ oid: 16_384, kind: 'r', partitionKey: null, viewDefinition: null }] },
      ],
      [
        'SELECT a.attname',
        {
          rows: [
            {
              name: 'id',
              dataType: 'bigint',
              isNotNull: true,
              expression: null,
              identity: 'a',
              generated: '',
            },
          ],
        },
      ],
      ['SELECT conname', { rows: [{ name: 'orders_pkey', definition: 'PRIMARY KEY (id)' }] }],
      [
        'SELECT pg_get_indexdef',
        { rows: [{ definition: 'CREATE INDEX i ON sales.orders USING btree (id)' }] },
      ],
    ])
    const sut = await connected()

    const ddl = await sut.objectDdl(ORDERS, ObjectKind.Table)

    expect(ddl).toBe(
      'CREATE TABLE "sales"."orders" (\n    "id" bigint GENERATED ALWAYS AS IDENTITY NOT NULL,\n    CONSTRAINT "orders_pkey" PRIMARY KEY (id)\n);\n\nCREATE INDEX i ON sales.orders USING btree (id);',
    )
    const queries = pg.clients[0]?.queries ?? []
    expect(queries.find((query) => query.sql.startsWith('SELECT c.oid'))?.values).toStrictEqual([
      'sales',
      'orders',
    ])
    expect(queries.find((query) => query.sql.startsWith('SELECT a.attname'))?.values).toStrictEqual(
      [16_384],
    )
  })

  it.each([
    ['v', 'CREATE OR REPLACE VIEW'],
    ['m', 'CREATE MATERIALIZED VIEW'],
  ])('should write a view of kind %s from its definition', async (kind, create) => {
    answerBy([
      [
        'SELECT c.oid',
        { rows: [{ oid: 1, kind, partitionKey: null, viewDefinition: ' SELECT 1;' }] },
      ],
    ])
    const sut = await connected()

    await expect(sut.objectDdl({ ...ORDERS, name: 'v' }, ObjectKind.View)).resolves.toBe(
      `${create} "sales"."v" AS\nSELECT 1;`,
    )
  })

  it('should say when the object does not exist', async () => {
    answerBy([['SELECT c.oid', { rows: [] }]])
    const sut = await connected()

    await expect(sut.objectDdl(ORDERS, ObjectKind.View)).rejects.toThrow(
      'PostgreSQL has no view named sales.orders',
    )
  })

  it('should read the catalog of another database with its own connection', async () => {
    answerBy([['SELECT c.oid', { rows: [] }]])
    const sut = await connected()

    await expect(sut.objectDdl({ ...ORDERS, database: 'crm' }, ObjectKind.Table)).rejects.toThrow(
      'no table',
    )
    expect(pg.clients[1]?.config).toMatchObject({ database: 'crm' })
  })
})
